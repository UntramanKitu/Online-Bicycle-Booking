from django.db import models
from django.contrib.auth.models import AbstractUser

# =========================================================================
# โมเดลตัวตนผู้ใช้งานหลัก (UnifiedUser)
# =========================================================================
# คลาส UnifiedUser เป็นโมเดลที่ใช้เก็บข้อมูลพื้นฐานของคนที่ล็อกอินเข้าระบบ (สืบทอดมาจาก AbstractUser)
# สาเหตุที่ต้องสืบทอดมาจาก AbstractUser ก็เพื่อให้เราใช้ระบบ Authentication เดิมของ Django ได้เลย 
# เช่น การเข้ารหัสรหัสผ่าน (Password hashing) หรือเซสชัน (Sessions) 
# แต่ยังสามารถปรับแต่งหรือเพิ่มฟังก์ชันใหม่ๆ ของเราเองเข้าไปได้

class UnifiedUser(AbstractUser):
    
    # ---------------------------------------------------------------------
    # @property ทำให้เราสามารถเรียกใช้ user.role ได้เหมือนเป็นตัวแปรทั่วไป (ไม่ต้องใส่วงเล็บ)
    # หน้าที่ของฟังก์ชันนี้คือ "เช็คสิทธิ์" (Role) ของผู้ใช้งานในปัจจุบัน เพื่อนำไปกำหนดการเข้าถึงหน้าเว็บต่างๆ
    # ---------------------------------------------------------------------
    @property
    def role(self):
        # เงื่อนไขที่ 1: ตรวจสอบว่าเป็น "เจ้าหน้าที่ (Staff)" หรือไม่?
        # - hasattr(self, 'staff_profile') คือเช็คว่ายูสเซอร์คนนี้มีข้อมูลตาราง StaffProfile ผูกอยู่หรือเปล่า
        # - self.staff_profile.status == 'ACTIVE' คือเช็คว่าแอดมินกด "อนุมัติ" สถานะเขาหรือยัง?
        if hasattr(self, 'staff_profile') and self.staff_profile.status == 'ACTIVE':
            # ถ้ายื่นขอสิทธิ์และถูกอนุมัติแล้ว จะคืนค่า "ระดับสิทธิ์" ในโปรไฟล์เจ้าหน้าที่ (เช่น MANAGER หรือ ADMIN)
            return self.staff_profile.access_level 
        
        # เงื่อนไขที่ 2: ตรวจสอบว่าเป็น Superuser หรือไม่?
        # (Superuser คือแอดมินสูงสุดที่สร้างผ่านคำสั่ง python manage.py createsuperuser ใน Terminal)
        if self.is_superuser:
            return 'ADMIN' # สิทธิ์สูงสุดครอบจักรวาล
            
        # เงื่อนไขที่ 3: ถ้าไม่ตรงกับเงื่อนไขใดเลย (ไม่ใช่เจ้าหน้าที่ และไม่ใช่ซุปเปอร์ยูสเซอร์)
        # ให้ถือว่าเป็นแค่นักศึกษา หรือ "ผู้ใช้งานทั่วไป (BASIC)"
        return 'BASIC'
        
    # ---------------------------------------------------------------------
    # ฟังก์ชันช่วยแปลงคำศัพท์สิทธิ์จากภาษาอังกฤษเป็น "ภาษาไทย" เพื่อนำไปแสดงบนหน้าเว็บให้คนอ่านเข้าใจง่าย
    # ---------------------------------------------------------------------
    def get_role_display(self):
        # สร้างพจนานุกรม (Dictionary) จับคู่คำ
        role_map = {
            'BASIC': 'ผู้ใช้ทั่วไป',
            'MANAGER': 'ผู้จัดการ',
            'ADMIN': 'ผู้ดูแลระบบ',
        }
        # ดึงค่าจากพจนานุกรม โดยดูจากค่า role ปัจจุบัน (ถ้าหาไม่เจอ ก็ให้ส่งค่า role ภาษาอังกฤษกลับไปเหมือนเดิม)
        return role_map.get(self.role, self.role)
