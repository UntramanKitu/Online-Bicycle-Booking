# -------------------------------------------------------------------------
# 1. ฟังก์ชันจัดการหน้าสมัครสมาชิก (Register)
# -------------------------------------------------------------------------
def register(request):
    # ตรวจสอบก่อนว่าผู้ใช้กดปุ่ม Submit (ส่งแบบฟอร์ม) มาหรือเปล่า? (POST)
    # หรือแค่คลิกเข้ามาเปิดหน้าเว็บดูเฉยๆ (GET)
    if request.method == 'POST':
        # ถ้ายื่นฟอร์มมา ให้นำข้อมูลใน request.POST ไปยัดใส่คลาส RegisterForm เพื่อตรวจสอบ
        form = RegisterForm(request.POST)
        
        # เช็คว่าข้อมูลถูกต้องตามกฎของโมเดลไหม? (เช่น รหัสผ่านตรงกันสองช่องไหม, กรอกอีเมลถูกรูปแบบไหม)
        if form.is_valid():
            # ถ้าถูกหมด ก็บันทึกผู้ใช้คนนี้ลงฐานข้อมูลได้เลย! (form.save() จะส่งคืนออบเจกต์ผู้ใช้กลับมา)
            user = form.save()
            
            # เมื่อสมัครเสร็จแล้ว ไม่ต้องให้ผู้ใช้เสียเวลาไปกรอกล็อกอินอีกรอบ
            # เรียกใช้ฟังก์ชัน login() ของ Django เพื่อล็อกอินผู้ใช้นี้เข้าสู่ระบบทันที
            login(request, user)
            
            # ฝากข้อความแจ้งเตือน (Flash Message) ไว้ในระบบ 
            # ซึ่งพอย้ายไปหน้าถัดไป ข้อความสีเขียวๆ นี้จะเด้งขึ้นมาบอกว่า "ลงทะเบียนสำเร็จ!"
            messages.success(request, 'ลงทะเบียนสำเร็จ! ยินดีต้อนรับเข้าสู่ระบบ')
            
            # สมัครเสร็จและล็อกอินแล้ว ให้ย้ายผู้ใช้ไปที่หน้า role_redirect เพื่อคัดแยกเส้นทาง
            return redirect('accounts:role_redirect') 
    else:
        # ถ้าเพิ่งเปิดหน้านี้ครั้งแรก (GET) ให้ส่งฟอร์มเปล่าๆ (ยังไม่กรอกอะไร) ไปแสดงบนหน้าจอ
        form = RegisterForm()
        
    # ดึงไฟล์ HTML (accounts/register.html) มาประมวลผล พร้อมกับแนบตัวแปร 'form' ไปวาดในหน้านั้นด้วย
    return render(request, 'accounts/register.html', {'form': form})

# -------------------------------------------------------------------------
# 2. ฟังก์ชันคัดแยกเส้นทางอัตโนมัติ (Role Redirect)
# -------------------------------------------------------------------------
# ทำไมต้องมีฟังก์ชันนี้?
# เพราะผู้ใช้ 1 คนตอนล็อกอินเสร็จ ระบบไม่รู้ว่าเขาเป็นนักศึกษา หรือแอดมิน เราจึงให้ทุกคนวิ่งมาหน้านี้เป็น "ด่านตรวจ" 
# ด่านนี้จะทำหน้าที่ตัดสินใจภายในเสี้ยววินาทีว่าควรส่งคนๆ นี้ไปที่หน้าไหนต่อ
def role_redirect(request):
    # ตรวจสอบชั้นแรก: ล็อกอินมาจริงๆ ใช่ไหม?
    if not request.user.is_authenticated:
        # ถ้าเป็นคนนอก ไม่ได้ล็อกอิน ให้ไล่กลับไปหน้า login ทันที
        return redirect('accounts:login')
        
    # ดึงสิทธิ์ (Role) ออกมาจากผู้ใช้ที่เพิ่งล็อกอินเข้ามา 
    # (เรียกใช้ @property role ในโมเดล UnifiedUser ที่เราเขียนไว้)
    role = request.user.role
    
    # ---------------------------------------------------
    # ด่านคัดกรอง:
    # ---------------------------------------------------
    if role == 'ADMIN':
        # ถ้าเป็น "แอดมินสูงสุด" มักจะอยากมาจัดการคน ให้เด้งไปหน้า "จัดการพนักงาน (staff_list)"
        return redirect('staff:staff_list')
        
    elif role == 'MANAGER':
        # ถ้าเป็น "เจ้าหน้าที่ทั่วไป" ปกติจะมาเพื่อโพสต์ข่าว ให้เด้งไปหน้า "จัดการประกาศ (manage_list)"
        return redirect('announcements:manage_list')
        
    else:
        # ถ้าไม่ใช่ทั้งสองอย่าง (เป็นนักศึกษา หรือผู้ใช้งาน BASIC) ก็ให้ไปโผล่ที่หน้า "หน้าแรก (อ่านประกาศ)" ปกติ
        return redirect('announcements:list')
